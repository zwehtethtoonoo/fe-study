SET NAMES utf8mb4;
USE fe_study;
CREATE TABLE IF NOT EXISTS topics (id VARCHAR(16) PRIMARY KEY, cat CHAR(1) NOT NULL, title VARCHAR(100) NOT NULL, summary VARCHAR(200) NOT NULL, summary_my VARCHAR(300) NOT NULL, sort INT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS terms (id INT AUTO_INCREMENT PRIMARY KEY, topic_id VARCHAR(16) NOT NULL, term VARCHAR(100) NOT NULL, meaning_my VARCHAR(300) NOT NULL, INDEX (topic_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS questions (id INT AUTO_INCREMENT PRIMARY KEY, topic_id VARCHAR(16) NOT NULL, body VARCHAR(500) NOT NULL, c1 VARCHAR(300) NOT NULL, c2 VARCHAR(300) NOT NULL, c3 VARCHAR(300) NOT NULL, c4 VARCHAR(300) NOT NULL, answer TINYINT NOT NULL, explain_ja VARCHAR(500) NOT NULL, explain_my VARCHAR(800) NOT NULL, sort INT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS progress (topic_id VARCHAR(16) PRIMARY KEY, done TINYINT NOT NULL DEFAULT 0, mark TINYINT NOT NULL DEFAULT 0) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS study_cards (id INT AUTO_INCREMENT PRIMARY KEY, front VARCHAR(255) COLLATE utf8mb4_bin NOT NULL, back VARCHAR(1000) COLLATE utf8mb4_bin NOT NULL, note TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (name VARCHAR(32) PRIMARY KEY, val VARCHAR(255) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS auth_tokens (token_hash CHAR(64) PRIMARY KEY, expires DATETIME NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
